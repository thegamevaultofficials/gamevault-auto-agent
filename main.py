def make_images():
    titles = ["छोटा फोन बड़ा सपना - 2017", "देसी यूट्यूबर्स की एंट्री", "500MB का जादू", "बैन का काला दिन 2022", "वापसी - इंडिया अवतार"]
    for i, title in enumerate(titles):
        img = Image.new('RGB', (1280, 720), color=(18, 18, 18))
        draw = ImageDraw.Draw(img)
        draw.rectangle([(40, 40), (1240, 680)], outline=(255, 200, 0), width=6)
        draw.text((80, 320), title, fill=(255,255,255))
        draw.text((80, 420), "GameVault", fill=(255,200,0))
        img.save(f"scene_{i}.jpg")
    print("5 visuals made")

def make_video():
    audio = AudioFileClip("gamevault_final.mp3")
    clips = []
    duration_per = audio.duration / 5
    for i in range(5):
        img_clip = ImageClip(f"scene_{i}.jpg", duration=duration_per)
        clips.append(img_clip)
    final = concatenate_videoclips(clips, method="compose")
    final = final.set_audio(audio)
    final.write_videofile("final_video.mp4", fps=24, codec='libx264', audio_codec='aac')
    print("FINAL VIDEO READY")

